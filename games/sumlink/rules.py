"""Python port of SumLink's matching rules.

Mirrors isValidPairFlat / findValidPairFlat from the game's
src/utils/gameLogic.js (verified identical in the Sep-30 bundled build).
Behaviour must stay byte-for-byte compatible with the JS, quirks included;
tests/test_rules.py checks this against fixtures generated by the real JS.

A board is the game's own JSON: a flat list of {"value": int|None, "state": str}
with state in {"active", "blurred", "cleared"}, 9 columns per row.
"""
COLS = 9
Board = list[dict]


def _active(board: Board, i: int) -> bool:
    return board[i] is not None and board[i].get("state") == "active"


def is_valid_pair(board: Board, i1: int, i2: int, cols: int = COLS) -> tuple[bool, str | None, list[int]]:
    """Returns (valid, match_type, blocking_indices)."""
    if not board or i1 >= len(board) or i2 >= len(board) or not board[i1] or not board[i2]:
        return False, None, []

    n1, n2 = board[i1].get("value"), board[i2].get("value")
    if n1 is None or n2 is None or (n1 != n2 and n1 + n2 != 10):
        return False, None, []

    r1, c1 = divmod(i1, cols)
    r2, c2 = divmod(i2, cols)

    if r1 == r2:
        blocking = [r1 * cols + c for c in range(min(c1, c2) + 1, max(c1, c2)) if _active(board, r1 * cols + c)]
        return (not blocking, "horizontal" if not blocking else None, blocking)

    if c1 == c2:
        blocking = [r * cols + c1 for r in range(min(r1, r2) + 1, max(r1, r2)) if _active(board, r * cols + c1)]
        return (not blocking, "vertical" if not blocking else None, blocking)

    if abs(r1 - r2) == abs(c1 - c2):
        r_step = 1 if r1 < r2 else -1
        c_step = 1 if c1 < c2 else -1
        r, c = r1 + r_step, c1 + c_step
        blocking = []
        while r != r2:
            if _active(board, r * cols + c):
                blocking.append(r * cols + c)
            r += r_step
            c += c_step
        return (not blocking, "diagonal" if not blocking else None, blocking)

    # "Sequential": neighbours in reading order once inactive cells are skipped.
    # This is how the end of one row links to the start of the next.
    active = [i for i in range(len(board)) if _active(board, i)]
    if i1 in active and i2 in active:
        p1, p2 = active.index(i1), active.index(i2)
        if abs(p1 - p2) == 1:
            return True, "sequential", []
        if p1 != p2:
            return False, None, active[min(p1, p2) + 1:max(p1, p2)]
    return False, None, []


def active_indices(board: Board) -> list[int]:
    return [i for i in range(len(board)) if _active(board, i)]


def find_valid_pairs(board: Board, cols: int = COLS) -> list[tuple[int, int]]:
    """All valid pairs, in the same order the game's hint search visits them."""
    act = active_indices(board)
    return [
        (act[a], act[b])
        for a in range(len(act))
        for b in range(a + 1, len(act))
        if is_valid_pair(board, act[a], act[b], cols)[0]
    ]


def find_valid_pair(board: Board, cols: int = COLS) -> tuple[int, int] | None:
    """First valid pair - identical to what the game's Hint button would show."""
    act = active_indices(board)
    for a in range(len(act)):
        for b in range(a + 1, len(act)):
            if is_valid_pair(board, act[a], act[b], cols)[0]:
                return act[a], act[b]
    return None


def is_stage_cleared(board: Board) -> bool:
    return all(c is not None and c.get("state") != "active" for c in board)


def is_out_of_moves(board: Board, add_rows_left: int) -> bool:
    """Same condition the game uses to show its 'Out of Moves!' popup."""
    return add_rows_left == 0 and find_valid_pair(board) is None


# ---------- board transitions (used for look-ahead and offline simulation) ----------

def _is_gone(cell: dict | None) -> bool:
    return bool(cell) and cell.get("state") in ("blurred", "cleared")


def compact_board(board: Board, cols: int = COLS) -> tuple[Board, list[int]]:
    """Port of compactBoard: drop rows with no active cells, pad with cleared cells.

    Returns (new_board, removed_row_numbers). Note the JS never keeps a row
    whose cells are all blurred/cleared, but only *reports* it as removed if
    it contains at least one blurred cell.
    """
    new_board: Board = []
    removed: list[int] = []
    for start in range(0, len(board), cols):
        row = board[start:start + cols]
        if not all(_is_gone(c) for c in row):
            new_board.extend(row)
            continue
        blurred = sum(1 for c in row if c.get("state") == "blurred")
        cleared = sum(1 for c in row if c.get("state") == "cleared")
        if blurred == len(row) or (1 <= blurred <= 9 and 1 <= cleared <= 9):
            removed.append(start // cols)
    while len(new_board) < len(board):
        new_board.append({"value": None, "state": "cleared"})
    return new_board, removed


def apply_match(board: Board, i1: int, i2: int) -> Board:
    """Board after a successful match: both cells blurred, then compacted."""
    new_board = list(board)
    new_board[i1] = {"value": board[i1]["value"], "state": "blurred"}
    new_board[i2] = {"value": board[i2]["value"], "state": "blurred"}
    return compact_board(new_board)[0]


def add_numbers(board: Board) -> Board:
    """Port of addNumbers: append copies of all active values after the last
    non-cleared cell. Values that don't fit in the 108 cells are dropped."""
    values = [c["value"] for c in board if c and c.get("state") == "active"]
    last = -1
    for i in range(len(board) - 1, -1, -1):
        if board[i].get("state") != "cleared":
            last = i
            break
    new_board = list(board)
    pos = last + 1
    for v in values:
        if pos >= len(new_board):
            break
        new_board[pos] = {"value": v, "state": "active"}
        pos += 1
    return new_board


def generate_board(stage: int, rng) -> Board:
    """Port of generateSeededGrid (despite the name, stages >= 2 are random).

    `rng` is a random.Random so simulations are reproducible.
    """
    board: Board = [{"value": None, "state": "cleared"} for _ in range(COLS * 12)]
    if stage == 1:
        layout = [(3, "active"), (4, "active"), (5, "blurred"), (5, "blurred"),
                  (6, "blurred"), (4, "blurred"), (4, "active"), (7, "active")]
        for i, (v, s) in enumerate(layout):
            board[i] = {"value": v, "state": s}
        return board
    if stage == 2:
        same = [n for i in range(1, 10) for n in (i, i)]
        while len(same) < 22:
            n = rng.randint(1, 9)
            same += [n, n]
        sums: list[int] = []
        while len(sums) < 14:
            sums += list(rng.choice([(1, 9), (2, 8), (3, 7), (4, 6)]))
        numbers = same + sums
        rng.shuffle(numbers)
    else:
        pairs = []
        for _ in range(4):
            pairs += [n for i in range(1, 10) for n in (i, i)]
            pairs += [n for i in range(1, 10) for n in (i, 10 - i)]
        rng.shuffle(pairs)
        numbers = pairs[:36]
    for i, n in enumerate(numbers):
        board[i] = {"value": n, "state": "active"}
    return board
